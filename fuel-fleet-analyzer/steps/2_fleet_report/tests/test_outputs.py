def test_report_uses_fuel_calc_import():
    """STRICT reuse check: Step 2 must import or invoke /app/fuel_calc.py via AST + string analysis."""
    found = False
    reuse_details = []
    checked_files = []

    for py_file in Path("/app").glob("*.py"):
        if py_file.name == "fuel_calc.py":
            continue
        checked_files.append(py_file.name)
        try:
            txt = py_file.read_text()
        except Exception:
            continue

        # AST-based checks
        try:
            import ast
            tree = ast.parse(txt)
            for node in ast.walk(tree):
                if isinstance(node, ast.Import):
                    for alias in node.names:
                        if "fuel_calc" in alias.name:
                            found = True
                            reuse_details.append(f"{py_file.name}: import {alias.name}")
                if isinstance(node, ast.ImportFrom):
                    if node.module and "fuel_calc" in node.module:
                        found = True
                        reuse_details.append(f"{py_file.name}: from {node.module} import ...")
                # Detect importlib.util.spec_from_file_location(..., "/app/fuel_calc.py") pattern via string in Call args not easy via AST, fallback to string check below
        except Exception:
            pass

        # String heuristic - import + usage
        if "fuel_calc" in txt and any(k in txt for k in ["calculate_fuel_needed", "calculate_cost", "importlib", "spec_from_file_location"]):
            found = True
            reuse_details.append(f"{py_file.name}: contains fuel_calc + usage keyword")
        # Subprocess CLI reuse is also valid
        if "fuel_calc.py" in txt and "subprocess" in txt:
            found = True
            reuse_details.append(f"{py_file.name}: subprocess calling fuel_calc.py")

    assert found, (
        "REUSE CHECK FAILED: Step 2 must import or invoke /app/fuel_calc.py from Step 1.\n"
        "Expected to find in /app/*.py (excluding fuel_calc.py) either:\n"
        "  - import fuel_calc via importlib.util.spec_from_file_location('fuel_calc', '/app/fuel_calc.py') and use calculate_fuel_needed/calculate_cost\n"
        "  - or subprocess.run(['python3', '/app/fuel_calc.py', ...])\n"
        f"Checked files in /app: {checked_files}\n"
        f"Reuse details found: {reuse_details}\n"
        "Do not re-implement formulas distance/mpg manually without importing fuel_calc."
    )



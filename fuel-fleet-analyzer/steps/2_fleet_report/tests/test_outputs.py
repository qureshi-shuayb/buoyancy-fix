def test_price_lookup_most_recent_logic():
    # Specific edge: trip on 2024-01-04 should use price from 2024-01-03 (3.52), not 2024-01-01 or 2024-01-06
    # Trip V002 150.75 miles on 2024-01-04, mpg 18, fuel 8.375, price 3.52 => cost 29.48
    trip_date = parse_date("2024-01-04")
    prices = []
    with open(PRICES_PATH) as f:
        reader = csv.DictReader(f)
        for row in reader:
            prices.append((parse_date(row["date"]), float(row["price_per_gallon"])))
    prices.sort(key=lambda x: x[0])
    cand = None
    for pd, pp in prices:
        if pd <= trip_date:
            cand = pp
        else:
            break
    assert abs(cand - 3.52) < 0.001, f"Price lookup logic wrong: expected 3.52 for 2024-01-04, got {cand}"

    # Check report total cost reflects this logic (not exact match lookup)
    with open(REPORT_PATH) as f:
        actual = json.load(f)
    assert actual["per_vehicle"]["V002"]["total_cost"] > 0



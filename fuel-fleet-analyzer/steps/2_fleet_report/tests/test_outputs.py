def test_price_lookup_fallback_before_first_price():
    """Fallback nuance: Trip before first price entry (e.g., 2023-12-31) must use first price 2024-01-01 $3.45"""
    early_date = parse_date("2023-12-31")
    prices = []
    with open(PRICES_PATH) as f:
        for row in csv.DictReader(f):
            prices.append((parse_date(row["date"]), float(row["price_per_gallon"])))
    prices.sort(key=lambda x: x[0])
    cand = None
    for pd, pp in prices:
        if pd <= early_date:
            cand = pp
        else:
            break
    if cand is None:
        cand = prices[0][1] if prices else 0.0
    assert abs(cand - 3.45) < 0.001, (
        f"FALLBACK PRICE LOOKUP FAILED: Trip on 2023-12-31 is before first price entry 2024-01-01, "
        f"so should use first price 3.45. Got {cand}. Did you handle candidate is None fallback?"
    )
    # If trips.csv contains early date, ensure report includes it
    with open(TRIPS_PATH) as f:
        has_early = any(row["date"] == "2023-12-31" for row in csv.DictReader(f))
    if has_early:
        expected = compute_expected()
        with open(REPORT_PATH) as fl:
            actual = json.load(fl)
        # V001 includes early trip now
        assert actual["per_vehicle"]["V001"]["total_miles"] >= expected["per_vehicle"]["V001"]["total_miles"] - 0.1, (
            f"Early trip 2023-12-31 not reflected: expected V001 miles >= {expected['per_vehicle']['V001']['total_miles']}, "
            f"got {actual['per_vehicle']['V001']['total_miles']}"
        )


